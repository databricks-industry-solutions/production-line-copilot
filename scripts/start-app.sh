#!/bin/bash
# Start the local Databricks App runtime pair (agent + AppKit server).
#
# Invoked by app launch entrypoints in dev/preview deployments.
# Optional env: AGENT_PORT, DATABRICKS_APP_PORT, SSE_USE_AI_SERVING_ONLY,
# SSE_USE_AI_SERVING_ONLY_FORCE_OFF, and app-name vars used for preview detection.
# Side effect: spawns background processes and forwards SIGTERM/SIGINT so both
# services shut down together.
set -euo pipefail

# Tier-1 Lakebase: Databricks/Lakebase may inject LAKEBASE_SYNCED_DATA_SCHEMA=public without mirror
# tables. Preview app names get SSE_USE_AI_SERVING_ONLY so reads use ai_serving.* (see lakebase_sync_config).
if [[ "${SSE_USE_AI_SERVING_ONLY_FORCE_OFF:-}" != "1" && -z "${SSE_USE_AI_SERVING_ONLY:-}" ]]; then
  _app="${DATABRICKS_APP_NAME:-}${APP_NAME:-}${DATABRICKS_APP_DEPLOYMENT_NAME:-}"
  _lc=$(printf '%s' "${_app}" | tr '[:upper:]' '[:lower:]')
  case "${_lc}" in *preview*)
    export SSE_USE_AI_SERVING_ONLY=true
    echo "[start-app] SSE_USE_AI_SERVING_ONLY=true (preview app bootstrap)"
    ;;
  esac
fi

# Ensure the AppKit server + client bundles exist. Deploying via
# `databricks apps deploy` (our bundle path) installs dependencies but does NOT
# run `npm run build`, and dist/ is gitignored (not shipped in the repo), so
# build it here on first start if it's missing. We invoke build:server +
# build:client directly (not `npm run build`) to skip the network-dependent
# `prebuild` appkit-sync step — types are already generated by the postinstall
# `typegen`, and appkit.plugins.json is committed.
if [[ ! -f "dist/server/server.js" || ! -f "client/dist/index.html" ]]; then
  echo "[start-app] dist/ missing — building AppKit server + client bundles..."
  npm run build:server
  npm run build:client
  echo "[start-app] Build complete."
fi

# Start Python agent server in background.
# Run source file directly to avoid stale console-script wrappers in reused virtualenvs.
echo "[start-app] Starting agent server on port ${AGENT_PORT:-8001}..."
uv run python agent_server/start_server.py --port ${AGENT_PORT:-8001} &
AGENT_PID=$!

# Start AppKit Node.js server (binds to $DATABRICKS_APP_PORT)
echo "[start-app] Starting AppKit server on port ${DATABRICKS_APP_PORT:-8000}..."
npm start &
APPKIT_PID=$!

# Propagate SIGTERM to both processes for graceful shutdown
cleanup() {
    echo "[start-app] Received signal, shutting down..."
    kill "$AGENT_PID" "$APPKIT_PID" 2>/dev/null
    wait "$AGENT_PID" "$APPKIT_PID" 2>/dev/null
    echo "[start-app] Shutdown complete."
}
trap cleanup SIGTERM SIGINT

# Fail fast: exit as soon as EITHER child dies so the platform restarts the
# whole container. Bare `wait` blocks on ALL children, which previously let a
# dead agent server hang undetected behind a still-alive AppKit server (the app
# kept serving HTML while every /api/* proxy call failed with "fetch failed").
# `wait -n` returns on the first child to exit; we then tear the other down and
# propagate a non-zero status to trigger a restart. The `if` wrapper keeps
# `set -e` from aborting before we can log which process died.
if wait -n; then
    EXIT_CODE=0
else
    EXIT_CODE=$?
fi

if ! kill -0 "$AGENT_PID" 2>/dev/null; then
    echo "[start-app] Agent server (pid $AGENT_PID) exited with status ${EXIT_CODE} — shutting down AppKit server to force a container restart."
else
    echo "[start-app] AppKit server (pid $APPKIT_PID) exited with status ${EXIT_CODE} — shutting down agent server to force a container restart."
fi

kill "$AGENT_PID" "$APPKIT_PID" 2>/dev/null
wait "$AGENT_PID" "$APPKIT_PID" 2>/dev/null
exit "${EXIT_CODE:-1}"
